NAZWY = ["DZUNGLA", "KANION", "TWIERDZA"]
CHODZ = set(".o-HgJMRN")

def sprawdz(nr, tekst):
    w = tekst.split("\n")
    assert all(len(r) == 14 for r in w), [(i, r) for i, r in enumerate(w) if len(r) != 14]
    # Wejście (ostatni wiersz) i ścieżka do wiersza 2 pod bramą bez przechodzenia przez S.
    from collections import deque
    start = (len(w) - 2, 7)
    assert w[start[0]][start[1]] in CHODZ
    q = deque([start]); seen = {start}
    while q:
        r, c = q.popleft()
        for dr, dc in ((1,0),(-1,0),(0,1),(0,-1)):
            rr, cc = r + dr, c + dc
            if 0 <= rr < len(w) and 0 <= cc < 14 and (rr, cc) not in seen and w[rr][cc] in CHODZ:
                seen.add((rr, cc)); q.append((rr, cc))
    assert (2, 6) in seen and (2, 7) in seen, "brak drogi do bramy"
    # Każda skrzynka i motocykl osiągalne / poprawne.
    for i, r in enumerate(w):
        if "M" in r:
            assert r in ("M" + "-" * 13, "-" * 13 + "M"), (nr, i, r)
        for c, ch in enumerate(r):
            if ch == "g": assert (i, c) in seen, ("skrzynka niedostepna", nr, i, c)
    cnt = {ch: sum(r.count(ch) for r in w) for ch in "SgJMRN"}
    print(nr, NAZWY[nr], len(w), "wierszy", cnt)
    return w

mapy = [sprawdz(i, m) for i, m in enumerate([M1, M2, M3])]

def dk():
    out = []
    for i, w in enumerate(mapy):
        out.append(f"fun mapa{i + 1}() -> List[str] = {{\n    var m: List[str];")
        for r in w:
            out.append(f'    m.push("{r}");')
        out.append("    return m;\n}\n")
    return "\n".join(out)

open("mapy.dk", "w").write(dk())
